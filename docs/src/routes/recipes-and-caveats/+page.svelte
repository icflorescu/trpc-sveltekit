<h3>Reserved path prefix</h3>

<p>
  Invoking the <code>createTRPCHandle</code> method reserves the <code>/trpc</code> path prefix for
  the tRPC API. This means that you cannot use this prefix for any other purpose. If you need to use
  this prefix for other purposes, you can use the <code>url</code> option to change the reserved prefix.
</p>

<h3>Prerendering</h3>

<p>
  The handle doesn't read <code>url.searchParams</code>, so it can be used in apps with prerendered
  pages. Keep in mind that procedure calls made from prerendered <code>load</code> functions run at build
  time.
</p>
